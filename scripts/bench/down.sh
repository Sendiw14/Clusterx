#!/usr/bin/env bash
# Remove the benchmark stack, its volume, its images and its generated secrets.
set -euo pipefail
. "$(dirname "$0")/env.sh"
grep -q '^# clusterx-bench' "$ROOT/.env" || { echo "$ROOT/.env was not generated by up.sh; refusing" >&2; exit 1; }
P=$(envval CLUSTERX_IMAGE_PREFIX)
dc --profile workers --profile monitoring --profile retention down -v --remove-orphans
docker image rm "$P/control-plane:local" "$P/worker:local" 2>/dev/null || true
rm -rf .secrets .secrets.env "$ROOT/.env"
